"""Generate blank overrides for vanilla files in folders the mod replaces.

Victoria 3 1.14 does not reliably honour ``game_custom_data.replace_paths`` from
``.metadata/metadata.json``: vanilla files in replaced folders are still loaded,
which pulls thousands of vanilla journal entries, events, histories, etc. into
the mod. A file in the mod with the same relative path as a vanilla file always
overrides it, so this script creates an intentionally blank file for every
vanilla script file that sits directly inside a replaced folder and is not
already provided by the mod.

Run it from the mod root after every game update (and commit the result):

    python docs/maintenance/vanilla_placeholders.py            # report + write
    python docs/maintenance/vanilla_placeholders.py --check    # report only
    python docs/maintenance/vanilla_placeholders.py --game "D:/Steam/steamapps/common/Victoria 3"

Existing placeholders whose vanilla counterpart no longer exists are reported
(``--prune`` deletes them).

A mod file whose name matches a vanilla file except for letter case is renamed to the vanilla
spelling: the game treats the two spellings as different files, and on a case-insensitive file
system both resolve to the mod file, which then runs twice (country histories applied twice).
"""
import argparse
import json
import os
import sys

DEFAULT_GAME = r"C:\Program Files (x86)\Steam\steamapps\common\Victoria 3"
MARKER = "# CWP placeholder"
PLACEHOLDER = (
    MARKER + ": intentionally blank.\n"
    "# Overrides the vanilla file of the same name because the mod replaces this folder\n"
    "# (see replace_paths in .metadata/metadata.json). Generated by docs/maintenance/vanilla_placeholders.py\n"
)
SCRIPT_EXTENSIONS = (".txt", ".gui", ".csv", ".asset", ".settings")
# Folders that are never loaded as game data.
SKIP_PREFIXES = ()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--game", default=DEFAULT_GAME, help="Victoria 3 install folder (containing game/)")
    parser.add_argument("--mod", default=os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
    parser.add_argument("--check", action="store_true", help="only report, do not write")
    parser.add_argument("--prune", action="store_true", help="delete placeholders whose vanilla file is gone")
    args = parser.parse_args()

    game = os.path.join(args.game, "game")
    if not os.path.isdir(game):
        sys.exit(f"Vanilla game folder not found: {game}")
    # DLCs are mounted on top of the base game, so their files in replaced folders leak into the mod as well
    content_roots = [game] + sorted(
        os.path.join(game, "dlc", d) for d in os.listdir(os.path.join(game, "dlc"))
        if os.path.isdir(os.path.join(game, "dlc", d))
    )
    with open(os.path.join(args.mod, ".metadata", "metadata.json"), encoding="utf-8-sig") as f:
        replace_paths = json.load(f)["game_custom_data"]["replace_paths"]

    created, stale, renamed = [], [], []
    for rel_dir in replace_paths:
        if rel_dir.startswith(SKIP_PREFIXES):
            continue
        mod_dir = os.path.join(args.mod, rel_dir)
        vanilla_files = set()
        for root in content_roots:
            vanilla_dir = os.path.join(root, rel_dir)
            if os.path.isdir(vanilla_dir):
                vanilla_files |= {
                    n for n in os.listdir(vanilla_dir)
                    if os.path.isfile(os.path.join(vanilla_dir, n)) and n.lower().endswith(SCRIPT_EXTENSIONS)
                }
        mod_names = {n.lower(): n for n in os.listdir(mod_dir)} if os.path.isdir(mod_dir) else {}
        for name in sorted(vanilla_files):
            target = os.path.join(mod_dir, name)
            existing = mod_names.get(name.lower())
            if existing is not None and existing != name:
                renamed.append(f"{rel_dir}/{existing} -> {name}")
                if not args.check:
                    tmp = target + ".casefix"
                    os.rename(os.path.join(mod_dir, existing), tmp)
                    os.rename(tmp, target)
                continue
            if os.path.exists(target):
                continue
            created.append(f"{rel_dir}/{name}")
            if not args.check:
                os.makedirs(mod_dir, exist_ok=True)
                with open(target, "w", encoding="utf-8-sig", newline="\n") as f:
                    f.write(PLACEHOLDER)
        if os.path.isdir(mod_dir):
            for name in os.listdir(mod_dir):
                path = os.path.join(mod_dir, name)
                if name in vanilla_files or not os.path.isfile(path):
                    continue
                with open(path, encoding="utf-8-sig", errors="replace") as f:
                    is_placeholder = f.read(len(MARKER)) == MARKER
                if is_placeholder:
                    stale.append(f"{rel_dir}/{name}")
                    if args.prune and not args.check:
                        os.remove(path)  # after closing it: Windows cannot delete an open file

    if renamed:
        print(f"{'Would rename' if args.check else 'Renamed'} {len(renamed)} file(s) to the vanilla letter case "
              "(stage the renames with git add -A):")
        for r in renamed:
            print("  ~", r)
    verb = "Would create" if args.check else "Created"
    print(f"{verb} {len(created)} placeholder(s).")
    for c in created:
        print("  +", c)
    if stale:
        print(f"{len(stale)} placeholder(s) no longer shadow a vanilla file" + (" (deleted)." if args.prune and not args.check else ":"))
        for s in stale:
            print("  -", s)
    return 1 if args.check and (created or renamed) else 0


if __name__ == "__main__":
    sys.exit(main())
